-- catalog_template: the standard equipment catalog and task library (.specs/features/catalog-seed/plan.md).
-- The template lives in private (door 1). private.seed_org_catalog copies it into one org, which then owns its
-- copy (door 2). Source: "Service included" in the maintenance proposal template, without the source company.

create table private.catalog_asset_types (
  code text primary key check (code ~ '^[A-Z][A-Z0-9_]*$'),
  name text not null
);

create table private.catalog_asset_type_tasks (
  code text not null references private.catalog_asset_types (code),
  position integer not null check (position >= 1),
  description text not null,
  primary key (code, position)
);

revoke all on private.catalog_asset_types, private.catalog_asset_type_tasks from public, anon, authenticated;

-- Door 3: codes are what Phase 2 synonyms map onto.

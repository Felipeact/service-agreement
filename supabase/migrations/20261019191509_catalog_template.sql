-- Copies the template into p_org, skipping codes the org already has, and returns the number of types inserted.
-- Tasks are copied only for the types this call inserted, so an existing type keeps its own checklist.
create function private.seed_org_catalog(p_org uuid) returns integer
language plpgsql
security invoker
set search_path = ''
as $$
declare
  n integer;
begin
  with inserted as (
    insert into public.asset_types (org_id, code, name)
    select p_org, c.code, c.name
    from private.catalog_asset_types c
    on conflict (org_id, code) do nothing
    returning id, code
  ),
  tasks as (
    insert into public.asset_type_tasks (org_id, asset_type_id, position, description)
    select p_org, i.id, t.position, t.description
    from inserted i
    join private.catalog_asset_type_tasks t on t.code = i.code
  )
  select count(*) into n from inserted;
  return n;
end $$;

revoke execute on function private.seed_org_catalog(uuid) from public, anon, authenticated;
